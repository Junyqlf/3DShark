namespace SandKill.Core
{
    /// <summary>卡牌类型。工人=平民牌，其余为角色牌。</summary>
    public enum CardType
    {
        Worker = 0,   // 工人：维持存活，全部失去则出局
        Undead,       // 亡灵：免疫攻击，被抽到时返回手牌；驱魔师可处决
        Exorcist,     // 驱魔师：每回合可抽对手一张牌，是亡灵则处决，否则归还
        Police,       // 警察：每回合可扣押对手一张牌，沉默1回合后归还
        Priest,       // 牧师：被抽走进入弃牌堆时触发亡语，从弃牌堆拿一张角色牌回手
        Guard,        // 侍卫：被攻击时可代替被抽中的牌进入弃牌堆（挡刀）
        Witch,        // 女巫：毒药=额外攻击一次；解药=从弃牌堆拿一张角色牌回手（各限一次）
        Arsenal,      // 军火库：每回合可额外攻击一次
        Hero,         // 英雄（2代）：永不离手；被攻击/扣押/勒索打中时改为扣1点HP
        ArmedGuard,   // 带刀侍卫（2代）：主动技，1回合内己方侍卫和大臣获得亡语"攻击1次"
        Minister,     // 大臣（2代）：主动技"贿赂"，交一张牌给一名玩家，对方1回合内不能攻击你
        GrandMinister, // 军机大臣（2代）：主动技"勒索"，获得其他所有人手牌中某种类型的全部牌
        Warden,       // 守卫（2代）：每回合可藏起一张手牌，不能连藏同一张、不能藏自己
        Maid,         // 侍女（2代）：无技能，免疫军火库的追加攻击
        GreenApple,   // 青苹果（2代）：受伤后2回合倒数，吃了回1HP；被攻击抽中时不进弃牌堆而是被抢走
        Terrorist,    // 恐怖分子（2代，2026-10-13 改版）：主动【安放炸弹】1蓝——2回合后爆炸，对每个敌手各1次无来源随机攻击（等同普攻，不记仇），自己同归于尽；被警察/PS沉默=拆弹+返还cd；被贿赂送人也不改目标
        // ---- 合成牌（2026-10-06）：消耗1行动点+配方3张牌合成，2点生命，合成后奖励抽1张 ----
        Priestess,    // 女祭司（苹果+女巫+牧师）：双限定技【复活】从弃牌堆复活1张角色牌 /【祈祷】2回合后自身1点生命转化为英雄1点生命
        Valkyrie,     // 女武神（侍卫+侍女+任意）：2点生命的挡刀身体；每挡1刀扣1点生命，耗尽进弃牌堆（2026-10-08 统一2HP结算）
        Paladin,      // 圣骑士（侍卫+牧师+任意）：2点生命的挡刀身体，每挡1刀扣1点生命；生命耗尽进弃牌堆时触发牧师亡语（回收1张角色牌）
        Jailer,       // 典狱长（守卫+警察+大臣）：【扣押】1行动点，把对方1张牌拿到自己手牌作人质并封印，1回合后归还解封（每回合限1次）
        Inquisitor,   // 审判官（驱魔师+牧师+侍女）：【审判】1行动点，随机揭示对手1张牌，是亡灵/女巫（异端）则处决
        // ---- 法术牌（3代·法术迸发，2026-10-20 用户设计）：释放后直接消耗（进弃牌堆）；
        //      未学会前是纯白板；升级得1技能点，learn 消耗1行动点+1回合学会一种法术 ----
        Alchemy,      // 炼金术（张数1）：通用法术（2026-10-22 中午重做）——【2026-10-23 退环境】枚举与定义保留，不进3代牌库
        Clarity,      // 清晰术（张数2）：看库顶3张选1——【2026-10-23 退环境】同上；其"标记"机制由点燃继承
        Ignite,       // 点燃（张数3，2026-10-23 重做）：看对手2张手牌选1张点燃——被点牌带2回合标记+2回合后1点伤害；选中军火库/英雄牌则直接1点伤害不产生标记
        Thunder,      // 雷霆（张数3，2026-10-21 用户裁定由4减至3）：1行动点，对选中的玩家连续攻击，次数=其当前手牌数的25%四舍五入
        Comet,        // 彗星（张数3，2026-10-21 用户裁定由4减至3）：不耗行动点；有人释放法术时，可消耗1张彗星抵消这个法术
        Barrier,      // 风墙（张数3；2026-10-23 由"屏障"更名重做）：1行动点，对一名玩家释放——获得持续2回合的2点定向护盾，只能吸收来自指定玩家的伤害
        Glacier,      // 冰川（张数2，2026-10-23 新增）：目标下2个回合合并为1个——回合照走但不刷新行动点与每回合限1次行动；不可叠加
        Heal          // 治疗术（张数3，2026-10-23 新增）：立刻回复英雄1点HP（替代青苹果生态位，与等级系统兼容）
    }

    public static class CardTypeExtensions
    {
        /// <summary>中文名。数据在 CardDefs 表里，这里只是查表入口（老调用处不用改）。</summary>
        public static string Name(this CardType t)
        {
            return CardDefs.Of(t).Name;
        }

        /// <summary>是否为角色牌（非工人）。牧师亡语、女巫解药只能回收角色牌。</summary>
        public static bool IsRole(this CardType t) { return CardDefs.Of(t).IsRole; }
    }
}
